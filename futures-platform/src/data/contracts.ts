export function getContractBySymbol(symbol: string): FuturesContract {
  const found = FUTURES_CONTRACTS.find((c) => c.symbol === symbol);
  return found ?? FUTURES_CONTRACTS[0];
}

export function roundToTick(price: number, tickSize: number): number {
  if (tickSize <= 0) return price;
  const rounded = Math.round(price / tickSize) * tickSize;
  const decimals = tickSize < 1 ? String(tickSize).split(".")[1]?.length ?? 2 : 0;
  return Number(rounded.toFixed(decimals));
}
